function theme(name, type, c) {
    const dark = type === 'dark';
    return {
        $schema: 'vscode://schemas/color-theme',
        name,
        type,
        semanticHighlighting: true,
        colors: workbench(c, dark),
        semanticTokenColors: semanticTokenColors(c),
        tokenColors: tokenColors(c, dark)
    };
}

export const THEMES = [
    { file: 'omg-dark-color-theme.json', theme: theme('OMG Dark', 'dark', MOCHA) },
    { file: 'omg-light-color-theme.json', theme: theme('OMG Light', 'light', LATTE) }
];

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    for (const t of THEMES) {
        writeFileSync(join(root, 'themes', t.file), JSON.stringify(t.theme, null, 2) + '\n');
        console.log('wrote themes/' + t.file);
    }
}
